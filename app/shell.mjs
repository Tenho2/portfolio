export function linkLinesFor(layout) {
  const ui = UI_THEMES.includes(layout);
  const first = ui ? "app/ui/base.css" : "app/app.css";
  const second = ui ? `app/ui/${layout}.css` : `app/layout-${layout}.css`;
  const note = ui
    ? [
        "    <!-- Experimental UI: a self-contained base plus one theme. Shares no",
        "         styling with app/app.css. -->",
      ]
    : [
        "    <!-- app/app.css is the shared design system: tokens, a11y utilities and",
        "         every component. Every shared layout loads it, so a component cannot diverge. -->",
      ];
  const shellNote = ui
    ? "    <!-- The theme: variables and identity rules only. -->"
    : "    <!-- The layout shell. May only rearrange what app/app.css defines. -->";
  return [
    "    <!-- stylesheets:begin (generated by tools/emit-pages.mjs, do not edit) -->",
    ...note,
    `    <link rel="stylesheet" href="${first}" />`,
    shellNote,
    `    <link rel="stylesheet" href="${second}" />`,
    "    <!-- stylesheets:end -->",
  ];
}

