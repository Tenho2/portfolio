/** Layouts that use the experimental app/ui/ stylesheets, not app/app.css. */
export const UI_THEMES = ["hud", "brutal", "editorial", "win31", "retro-desktop"];

/** The filename for a layout name, used by the switcher to build its href. */
export const fileFor = (name) => {
  const hit = LAYOUTS.find((l) => l.name === name);
  return hit ? hit.file : LAYOUTS[0].file;
};

/**
 * Stylesheet links for one layout, injected before </head>.
 *
 * The three original layouts load the shared design system app/app.css plus a
 * layout sheet that may only rearrange it. The four experimental layouts load
 * app/ui/base.css plus their own theme: they intentionally share no styling
 * with app/app.css.
 *
 * Wrapped in sentinel comments so the generator can excise exactly its own
 * output on the next run.
 */
export function linkLinesFor(layout) {
  const ui = UI_THEMES.includes(layout);
  const first = ui ? "app/ui/base.css" : "app/app.css";
  const second = ui ? `app/ui/${layout}.css` : `app/layout-${layout}.css`;
  const note = ui
    ? [
        "    <!-- Experimental UI: a self-contained base plus one theme. Shares no",
        "         styling with app/app.css. -->",
      ]
    : [
        "    <!-- app/app.css is the shared design system: tokens, a11y utilities and",
        "         every component. Every shared layout loads it, so a component cannot diverge. -->",
      ];
  const shellNote = ui
    ? "    <!-- The theme: variables and identity rules only. -->"
    : "    <!-- The layout shell. May only rearrange what app/app.css defines. -->";
  return [
    "    <!-- stylesheets:begin (generated by tools/emit-pages.mjs, do not edit) -->",
    ...note,
    `    <link rel="stylesheet" href="${first}" />`,
    shellNote,
    `    <link rel="stylesheet" href="${second}" />`,
    "    <!-- stylesheets:end -->",
  ];
}

